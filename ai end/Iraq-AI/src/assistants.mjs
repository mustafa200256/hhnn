export const ASSISTANT_IDS = Object.keys(ASSISTANTS);

export function assistantInfo() {
  return ASSISTANT_IDS.map((id) => ({ id, name: ASSISTANTS[id].name }));
}

export function systemPromptFor(assistantId) {
  const a = ASSISTANTS[assistantId] || ASSISTANTS.general;
  return `${basePrompt()}\n\n${a.prompt}`;
}
